/// Reverses each 32-bit word of a 16-byte block (K5TOOL `ReverseBytesU32`).
fn reverse_u32_words(data: &[u8; 16]) -> [u8; 16] {
    let mut out = [0u8; 16];
    for i in 0..4 {
        out[i * 4] = data[i * 4 + 3];
        out[i * 4 + 1] = data[i * 4 + 2];
        out[i * 4 + 2] = data[i * 4 + 1];
        out[i * 4 + 3] = data[i * 4];
    }
    out
}

/// Returns the reversed `(key, iv)` for `key_number` (0..15).
fn key_iv(key_number: u8) -> ([u8; 16], [u8; 16]) {
    let k = KEYS[key_number as usize * 2];
    let iv = KEYS[key_number as usize * 2 + 1];
    (reverse_u32_words(&k), reverse_u32_words(&iv))
}

/// Streaming AES-128-CBC (no padding) encryptor chained across the whole image.
pub(super) struct AesStream {
    enc: Aes128CbcEnc,
}

impl AesStream {
    pub(super) fn new(key: &[u8; 16], iv: &[u8; 16]) -> Self {
        Self {
            enc: Aes128CbcEnc::new_from_slices(key, iv).expect("AES-128 key and IV are 16 bytes"),
        }
    }

    /// Encrypts `buf` (length a multiple of 16) in place, chaining CBC state.
    pub(super) fn encrypt(&mut self, buf: &mut [u8]) {
        let (blocks, rest) = buf.as_chunks_mut::<16>();
        debug_assert!(rest.is_empty(), "AES-CBC input must be a multiple of 16");
        for block in blocks {
            self.enc.encrypt_block(block.into());
        }
    }
}

/// AES-CBC-128 flash protocol (bootloader beacon `0x057a`).
pub struct ProtocolV5 {
    key_number: u8,
    stream: Option<AesStream>,
}

impl ProtocolV5 {
    /// Creates a V5 protocol handler using AES key pair `key_number`.
    ///
    /// key numbers above 15 are clamped to 15.
    pub fn new(key_number: u8) -> Self {
        Self {
            key_number: key_number.min(15),
            stream: None,
        }
    }
}

impl FlashProtocol for ProtocolV5 {
    fn ack_id(&self) -> u16 {
        0x057c
    }

    fn version_packet(&self, version: &str) -> Vec<u8> {
        let mut p = vec![0x7d, 0x05, 0x14, 0x00];
        let mut field = [0u8; 16];
        let bytes = version.as_bytes();
        let n = bytes.len().min(16);
        field[..n].copy_from_slice(&bytes[..n]);
        p.extend_from_slice(&field);
        p.push(self.key_number);
        p.extend_from_slice(&[0x00, 0x00, 0x00]);
        p
    }

    fn begin(&mut self) {
        let (key, iv) = key_iv(self.key_number);
        self.stream = Some(AesStream::new(&key, &iv));
    }

    fn write_packet(
        &mut self,
        chunk_no: u16,
        chunk_count: u16,
        block: &[u8; FLASH_BLOCK],
        len: u16,
        id: u32,
    ) -> Vec<u8> {
        if self.stream.is_none() {
            self.begin();
        }
        let stream = self.stream.as_mut().expect("stream initialized above");
        let mut cipher = *block;
        stream.encrypt(&mut cipher);
        make_write_payload(0x7b, chunk_no, chunk_count, &cipher, len, id)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::flash::WRITE_ID;

    #[test]
    fn version_packet_layout() {
        let p = ProtocolV5::new(3).version_packet("5.00.05");
        assert_eq!(&p[0..4], &[0x7d, 0x05, 0x14, 0x00]);
        assert_eq!(&p[4..11], b"5.00.05");
        assert_eq!(p[20], 3); // key_number after 16 version bytes
        assert_eq!(p.len(), 24);
    }

    #[test]
    fn write_packet_encrypts_and_uses_0x7b() {
        let block = [0u8; FLASH_BLOCK];
        let mut proto = ProtocolV5::new(0);
        proto.begin();
        let p = proto.write_packet(0, 1, &block, 0x100, WRITE_ID);
        assert_eq!(p[0], 0x7b);
        // Ciphertext of an all-zero block is not all-zero.
        assert!(p[16..].iter().any(|&b| b != 0));
    }
}

