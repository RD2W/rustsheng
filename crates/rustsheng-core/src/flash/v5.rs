        // KEYS[0] = e16e0d29 e0c83418 987f9433 f5ff620e
        // reversed per u32 word -> 290d6ee1 1834c8e0 33947f98 0e62fff5
        // KEYS[1] = 14b7a2be 0223e259 b2066d88 86977e36
